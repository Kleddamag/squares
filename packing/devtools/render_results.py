#!/usr/bin/env python3
"""Generate `frontier/RESULTS.md`: the register's results, prioritized.

`results.yaml` is the record and `epistemics.md` owns its vocabulary; this view
is the one prioritized surface the reader tier points at, sorted by
significance descending, then confirmation descending, then id.
`devtools/check_results.py` grants the rungs; this file only displays them,
and the gate fails when the committed view drifts from the register.

This project's results come first. Results by others follow in the lineage their
sources state, read from the bibliography rather than restated: building on this
project, crediting it second-hand, independent of it, and published before it began.
Within each group the entries still waiting on a replay here (`C` below `C3`) come
first, since they are the queue. Their credit and published date are shown beside the
rungs, with the result's standing, derived from the case records and never stored by
`devtools.render_recent_results.standing`, the same function README's tables use:
whether a case bound rests on it now, and if not, whether it was superseded or is a
second certificate for a value another result holds.

The grouping and its order are `grouped_results`, which the site's overview calls too, so
its results table and this view cannot sort or group a result differently.

Usage, from `packing/`:
    uv run --frozen --all-extras --group dev python -m devtools.render_results --update
    uv run --frozen --all-extras --group dev python -m devtools.render_results --check
"""

from __future__ import annotations

import argparse
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any, NamedTuple

from strif import atomic_output_file

from devtools.render_recent_results import load_records, standing
from devtools.result_credit import OTHERS, credit_line, source_lineage
from sqpack.yamlio import safe_load

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "frontier" / "results.yaml"
BIBLIOGRAPHY = ROOT / "resources" / "bibliography.yaml"
OUTPUT = ROOT / "frontier" / "RESULTS.md"

#: The typographic apostrophe the register's prose uses, written as an escape for the
#: reason `tests/test_generated_table_typography.py` gives: a literal one is invisible in a
#: diff and ambiguous on sight.
APOSTROPHE = "\u2019"

HEADER = """# Results

<!-- GENERATED by devtools.render_results --update from results.yaml. Do not edit. -->

One row per registered result: this project's first, then results by others grouped
by the lineage their sources state, each sorted by significance, then confirmation.
The axes are defined in [`epistemics.md`](../../epistemics.md): `V` is the
highest verification rung supported by the cited evidence, `C` what this
repository has recorded or performed, `S` a judged score that never gates,
and novelty a scoped source-search classification.
`devtools/check_results.py` validates the structural support and required
explanations for every declared `V` and `C`.
"""


#: The group this project's own results read under, and its heading.
OURS = "this-project"
OURS_TITLE = f"This Project{APOSTROPHE}s Results"
#: The key of the group `result_credit.OTHERS` titles with no lineage: results by others
#: published before this project began.
BEFORE_PROJECT = "before-project"


class Group(NamedTuple):
    """One heading of the view and its results, in the order the view lists them."""

    key: str
    title: str
    records: list[Mapping[str, Any]]


def scope(record: Mapping[str, Any]) -> str:
    """The `n` a result speaks about, as the view's `n` column prints it."""
    values = record["scope"]
    if "n_values" in values:
        return ", ".join(str(n) for n in values["n_values"])
    return f"{values['n_min']}-{values['n_max']}"


def claim(record: Mapping[str, Any]) -> str:
    """The claim on one line, with a pipe escaped for a table cell."""
    return " ".join(str(record["claim"]).split()).replace("|", r"\|")


def order(record: Mapping[str, Any]) -> tuple[int, int, str]:
    """Significance descending, then confirmation descending, then id."""
    return (-record["significance"]["score"], -int(record["confirmation"][1]), record["id"])


def grouped_results(
    results: Sequence[Mapping[str, Any]], sources: Mapping[str, Mapping[str, Any]]
) -> list[Group]:
    """The register's results under the view's headings, each group in the view's order.

    This project's results come first, always, even when there are none. Results by others
    follow in the lineage their sources state, `result_credit.OTHERS`, and only the groups
    that hold a result; within each, the entries still waiting on a replay here (`C` below
    `C3`) come first, since they are the queue.
    """
    ordered = sorted(results, key=order)
    groups = [Group(OURS, OURS_TITLE, [r for r in ordered if not r.get("attribution")])]
    others = [record for record in ordered if record.get("attribution")]
    for lineage, title in OTHERS:
        group = sorted(
            (record for record in others if source_lineage(record, sources) == lineage),
            key=lambda record: (int(record["confirmation"][1]) >= 3, *order(record)),
        )
        if group:
            groups.append(Group(lineage or BEFORE_PROJECT, title, group))
    return groups


def render() -> str:
    register = safe_load(RESULTS.read_text(encoding="utf-8"))
    sources = {
        source["key"]: source
        for source in safe_load(BIBLIOGRAPHY.read_text(encoding="utf-8"))["sources"]
    }
    results = sorted(register["results"], key=order)
    ours, *others = grouped_results(results, sources)
    lines = [HEADER]
    lines.append(f"## {ours.title}")
    lines.append("")
    lines.append("| id | n | V | C | S | novelty | claim |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- |")
    lines.extend(
        f"| {record['id']} | {scope(record)} | {record['verification']} "
        f"| {record['confirmation']} | S{record['significance']['score']} "
        f"| {record['novelty']} | {claim(record)} |"
        for record in ours.records
    )
    lines.append("")
    if others:
        records = load_records()
        lines.append("## Results by Others")
        lines.append("")
        lines.append(
            f"Credit is the source{APOSTROPHE}s, as the bibliography records it; `V` and `C` "
            f"are this register{APOSTROPHE}s, so an entry below `C3` is still waiting on a "
            "complete replay here."
        )
        lines.append("")
        for group in others:
            lines.append(f"### {group.title}")
            lines.append("")
            lines.append("| id | n | credit | published | V | C | S | standing | claim |")
            lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
            lines.extend(
                f"| {record['id']} | {scope(record)} | {credit_line(record, sources)} "
                f"| {record['attribution']['published']} | {record['verification']} "
                f"| {record['confirmation']} | S{record['significance']['score']} "
                f"| {standing(record, records)} | {claim(record)} |"
                for record in group.records
            )
            lines.append("")
    lines.append("## Next actions")
    lines.append("")
    lines.append("The next evidence-improving action or terminal rationale for each result:")
    lines.append("")
    for record in results:
        next_rung = " ".join(str(record["next_rung"]).split())
        lines.append(f"- **{record['id']}** — {next_rung}")
    lines.append("")
    lines.append(f"Register reviewed {register['last_reviewed']}.")
    lines.append("")
    lines.append("<!-- This document follows common-doc-guidelines.md.")
    lines.append("See github.com/jlevy/practical-prose and review guidelines before editing.")
    lines.append("-->")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--update", action="store_true")
    group.add_argument("--check", action="store_true")
    options = parser.parse_args()
    rendered = render()
    if options.update:
        with atomic_output_file(OUTPUT) as temporary:
            temporary.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT.parent)}")
        return 0
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
        relative = OUTPUT.relative_to(ROOT.parent)
        print(f"{relative} is stale; run devtools.render_results --update")
        return 1
    print(f"{OUTPUT.relative_to(ROOT.parent)} agrees with results.yaml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
